/**
 * Документы набора: [{genre, name, docx, gold}].
 * @returns {{genre: string, name: string, docx: Uint8Array, gold: any}[]}
 */
export function buildHeldoutDocs() {
  return DOCS.map((d) => {
    const ents = [...d.gold, ...(EXTRA[d.name] || []), ...(d.inn || []).map((v) => ({ cat: 'INN', value: v }))];
    const gold = {
      entities: ents.map((e, i) => ({
        key: `e${i + 1}`,
        category: e.cat,
        value: e.value,
        ...(e.surname ? { surname: e.surname } : {}),
        ...(e.parts?.length ? { parts: e.parts } : {}),
        ...(e.modelOnly ? { modelOnly: true } : {}),
        ...(e.vocative ? { vocative: true } : {}),
      })),
      negatives: d.neg.map((n) => ({ value: n.value, category: n.cat === 'any' ? 'PERSON' : n.cat })),
      ...(d.neutral ? { neutral: d.neutral } : {}),
    };
    return { genre: GENRE[d.name], name: d.name, docx: makeDocx(d.body.join('')), gold };
  });
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const outArg = process.argv.find((a) => a.startsWith('--out='));
  const out = resolve(outArg ? outArg.slice('--out='.length) : HELDOUT_DIR);
  for (const d of buildHeldoutDocs()) {
    const dir = join(out, d.genre);
    mkdirSync(dir, { recursive: true });
    writeFileSync(join(dir, `${d.name}.docx`), d.docx);
    writeFileSync(join(dir, `${d.name}.gold.json`), JSON.stringify(d.gold, null, 2) + '\n');
    console.log(`${d.genre}/${d.name}: gold ${d.gold.entities.length}/${d.gold.negatives.length}`);
  }
}
