export const STOP_PREFIX = STOP_PREFIX_LIST.map(lowerE);

/** Слово — шаблонное (не может быть частью ФИО/названия). */
export function isStopWord(word) {
  const w = lowerE(word).replace(/\.$/, '');
  if (STOP_EXACT.has(w)) return true;
  for (const p of STOP_PREFIX) {
    // короткие основы («суд», «акт», «банк», «город») — только с короткими окончаниями, чтобы не задеть «Судаков», «Городецкий»
    if (w.startsWith(p) && (p.length > 5 || w.length - p.length <= 3)) return true;
  }
  return false;
}

