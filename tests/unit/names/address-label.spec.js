// WP11-D (ревью, отложенный набор): адрес после адресной метки — до конца строки или предложения, в том числе без «ул.»
// и «д.»; «Город, Улица 12-5» без типов — weak; второй адрес «…по адресу: г. Казань, ул. Чистопольская, д. 61, кв. 88»
// не теряет дом. Все адреса вымышленные.
import { describe, it, expect } from 'vitest';
import { findAddresses } from '../../../src/core/detect/names/address.js';

const found = (t) => findAddresses(t).map((a) => `${a.confidence}:${t.slice(a.start, a.end)}`);

describe('адрес после метки (labeled)', () => {
  it('метка, двоеточие или тире — значение до конца строки', () => {
    expect(found('Адрес: Москва, Тверская 12-5')).toEqual(['labeled:Москва, Тверская 12-5']);
    expect(found('Доставка: Пермь, Ленина 54/2')).toEqual(['labeled:Пермь, Ленина 54/2']);
    expect(found('Адрес регистрации: Тюмень, Республики 61')).toEqual(['labeled:Тюмень, Республики 61']);
    expect(found('Место жительства — Самарская область, Сызрань, Советская 7')).toEqual(['labeled:Самарская область, Сызрань, Советская 7']);
    expect(found('Проживаю по адресу Новосибирск, Красный проспект 25')).toEqual(['labeled:Новосибирск, Красный проспект 25']);
    expect(found('Lives at 12 Rue de Rivoli, Paris')).toEqual(['labeled:12 Rue de Rivoli, Paris']);
    expect(found('Address: 221B Baker Street, London')).toEqual(['labeled:221B Baker Street, London']);
  });

  it('слова между меткой и двоеточием; конец предложения; стоп на строчном слове не из типов адреса', () => {
    expect(found('2. Почтовый адрес Заказчика для корреспонденции: Тольятти, Революционная 52-14.')).toEqual(['labeled:Тольятти, Революционная 52-14']);
    const t =
      'Я, Хайруллин Ринат Ильдарович, проживающий по адресу: Республика Татарстан, г. Казань, ул. Баумана, д. 9, кв. 3, уполномочиваю Сафину Гульнару Маратовну, проживающую по адресу: г. Казань, ул. Чистопольская, д. 61, кв. 88, представлять мои интересы.';
    expect(found(t)).toEqual(['labeled:Республика Татарстан, г. Казань, ул. Баумана, д. 9, кв. 3', 'labeled:г. Казань, ул. Чистопольская, д. 61, кв. 88']);
  });

  it('не адрес: почта, сайт, дата, текст со строчной, город без номера', () => {
    for (const t of [
      'Адрес электронной почты: info@example.test',
      'Адрес сайта: https://example.test',
      'Товарный знак зарегистрирован: 12.05.2015 в реестре',
      'Доставка займёт 2 дня.',
      'Доставка — курьером Сергеем Вдовиным.',
      'Адрес: Москва',
    ])
      expect(found(t), t).toEqual([]);
  });
});

describe('«Город, Улица 12-5» без типов (weak)', () => {
  it('город, улица с заглавной и номер дома', () => {
    expect(found('Тольятти, Революционная 52-14')).toEqual(['weak:Тольятти, Революционная 52-14']);
    expect(found('Пишите: Воронеж, Лесная 14')).toEqual(['weak:Воронеж, Лесная 14']);
  });
  it('не адрес: номер пункта, сумма, шаблонное слово, «ул. Ленина, д. 1» без метки и индекса', () => {
    for (const t of ['Итого, Сумма 500', 'ул. Ленина, д. 1', 'Москва, Россия', 'Раздел 2, Пункт 3.1']) expect(found(t), t).toEqual([]);
  });
  it('английский адрес с «Flat»', () => {
    expect(found('Flat 4, 27 Elgin Crescent, London W11 2JD | +44 20 7946 0532')).toEqual(['weak:Flat 4, 27 Elgin Crescent, London W11 2JD']);
  });
});

describe('ревью WP11-D (3): дом и квартира после запятой, «расположенную:», британский адрес без типа улицы', () => {
  it('адрес продлевается через «, N», «, кв./корпус/строение N»', () => {
    expect(found('квартиру, расположенную: Ярославль, проспект Октября, 48, кв. 17.')).toEqual(['labeled:Ярославль, проспект Октября, 48, кв. 17']);
    expect(found('Заказ № 5514: Мытищи, Олимпийский проспект, 10.')).toEqual(['weak:Мытищи, Олимпийский проспект, 10']);
    expect(found('Оборудование передано на объекте: Калуга, Грабцевское шоссе 35, строение 2.')).toEqual(['weak:Калуга, Грабцевское шоссе 35, строение 2']);
    expect(found('Склад, находящийся: Тула, Пролетарская 12, корпус 3')).toEqual(['labeled:Тула, Пролетарская 12, корпус 3']);
    // не часть адреса: дата и сумма после запятой
    expect(found('Адрес: Тула, Пролетарская 12, 15 сентября 2026 г.')).toEqual(['labeled:Тула, Пролетарская 12']);
  });
  it('«Suite 5, 88 Deansgate, Manchester M3 2ER» и «88 Deansgate, Manchester M3 2ER»', () => {
    expect(found('Suite 5, 88 Deansgate, Manchester M3 2ER')).toEqual(['weak:Suite 5, 88 Deansgate, Manchester M3 2ER']);
    expect(found('88 Deansgate, Manchester M3 2ER')).toEqual(['weak:88 Deansgate, Manchester M3 2ER']);
    expect(found('We shipped 5 Boxes, as agreed.')).toEqual([]);
  });
});
